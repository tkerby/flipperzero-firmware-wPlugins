"""Quantise a trained model to int8 (one scale per row) and write C sources.

usage: python export.py composer.pt ../composer_weights.c ../composer_weights.h
Also writes quantised.npz, used by reference.py.
"""
import sys

import numpy as np
import torch

from model import Composer

TENSORS = [
    # C name, state_dict key
    ("cm_emb_pitch", "emb_pitch.weight"),
    ("cm_emb_dur", "emb_dur.weight"),
    ("cm_emb_beat", "emb_beat.weight"),
    ("cm_emb_bar", "emb_bar.weight"),
    ("cm_emb_style", "emb_style.weight"),
    ("cm_gru_w_ih", "gru.weight_ih_l0"),
    ("cm_gru_w_hh", "gru.weight_hh_l0"),
    ("cm_head_pitch_w", "head_pitch.weight"),
    ("cm_emb_pitch2", "emb_pitch2.weight"),
    ("cm_head_dur_w", "head_dur.weight"),
]
BIASES = [
    ("cm_gru_b_ih", "gru.bias_ih_l0"),
    ("cm_gru_b_hh", "gru.bias_hh_l0"),
    ("cm_head_pitch_b", "head_pitch.bias"),
    ("cm_head_dur_b", "head_dur.bias"),
]


def quantise(m):
    scale = np.abs(m).max(axis=1) / 127.0
    scale[scale == 0] = 1.0
    q = np.clip(np.round(m / scale[:, None]), -127, 127).astype(np.int8)
    return q, scale.astype(np.float32)


def c_array(ctype, name, values, per_line=16):
    body = ",\n".join("    " + ", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line))
    return f"const {ctype} {name}[{len(values)}] = {{\n{body}\n}};\n"


def main():
    src, c_path, h_path = sys.argv[1:4]
    state = Composer().state_dict()
    state.update(torch.load(src, map_location="cpu"))
    arrays, npz, total = [], {}, 0
    header = ["#pragma once", "", "#include <stdint.h>", "",
              "/* Generated by training/export.py - do not edit. */", ""]
    for name, key in TENSORS:
        m = state[key].numpy().astype(np.float32)
        q, scale = quantise(m)
        npz[name], npz[name + "_scale"] = q, scale
        arrays.append(c_array("int8_t", name, [str(int(v)) for v in q.flatten()]))
        arrays.append(c_array("float", name + "_scale", [f"{v:.9g}f" for v in scale]))
        header += [f"extern const int8_t {name}[{q.size}];", f"extern const float {name}_scale[{scale.size}];"]
        total += q.size + 4 * scale.size
    for name, key in BIASES:
        b = state[key].numpy().astype(np.float32)
        npz[name] = b
        arrays.append(c_array("float", name, [f"{v:.9g}f" for v in b]))
        header.append(f"extern const float {name}[{b.size}];")
        total += 4 * b.size
    with open(c_path, "w") as f:
        f.write('/* Generated by training/export.py - do not edit. */\n#include "composer_weights.h"\n\n')
        f.write("\n".join(arrays))
    with open(h_path, "w") as f:
        f.write("\n".join(header) + "\n")
    np.savez("quantised.npz", **npz)
    print(f"weights: {total} bytes")


if __name__ == "__main__":
    main()
